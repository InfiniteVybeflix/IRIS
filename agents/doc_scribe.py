#!/usr/bin/env python3
"""
doc_scribe.py — QUILL
Technical Writing Agent for IRIS v1.0
Report generation, Markdown/Word/PDF export, auto-docs from code (AST parsing),
presentation generation (reveal.js/marp), changelog generation.
"""

import threading
import hashlib
import json
import logging
import time
import os
import subprocess
import re
import ast
from typing import Dict, Any, List, Tuple, Optional
from datetime import datetime

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger("QUILL")


class DocScribe:
    CODENAME = "QUILL"

    def __init__(self, commander_bus=None, shared_memory=None):
        self._lock = threading.RLock()
        self._running = False
        self._commander_bus = commander_bus
        self._shared_memory = shared_memory
        self._session_id = hashlib.sha256(f"{self.CODENAME}{time.time()}".encode()).hexdigest()[:16]
        logger.info(f"[{self.CODENAME}] Session {self._session_id} initialized.")

    def start(self) -> bool:
        with self._lock:
            if self._running:
                return True
            self._running = True
            self._report_to_commander("QUILL started", level="info")
            return True

    def stop(self) -> bool:
        with self._lock:
            if not self._running:
                return True
            self._running = False
            self._report_to_commander("QUILL stopped", level="info")
            return True

    def health(self) -> Dict[str, Any]:
        with self._lock:
            return {
                "agent": self.CODENAME,
                "session_id": self._session_id,
                "running": self._running,
                "timestamp": datetime.utcnow().isoformat(),
            }

    def _report_to_commander(self, message: str, level: str = "info", data: Any = None) -> None:
        payload = {
            "agent": self.CODENAME,
            "session_id": self._session_id,
            "timestamp": datetime.utcnow().isoformat(),
            "level": level,
            "message": message,
            "data": data,
        }
        if self._commander_bus:
            try:
                self._commander_bus.publish(f"agent.{self.CODENAME}", payload)
            except Exception as e:
                logger.error(f"[{self.CODENAME}] Bus error: {e}")
        else:
            logger.log(getattr(logging, level.upper(), logging.INFO), f"[{self.CODENAME}] {message}")

    def _store_memory(self, key: str, value: Any) -> None:
        if self._shared_memory:
            try:
                self._shared_memory.set(f"{self.CODENAME}.{key}", value, ttl=86400)
            except Exception as e:
                logger.error(f"[{self.CODENAME}] Memory store error: {e}")

    def _execute_shell(self, command: str, timeout: int = 60) -> Tuple[int, str, str]:
        try:
            proc = subprocess.run(command, shell=True, capture_output=True, text=True, timeout=timeout)
            return proc.returncode, proc.stdout, proc.stderr
        except subprocess.TimeoutExpired:
            return -1, "", f"Command timed out after {timeout}s"
        except Exception as e:
            return -1, "", str(e)

    # ------------------------------------------------------------------
    # Capabilities
    # ------------------------------------------------------------------
    def generate_report(self, title: str, sections: List[Dict[str, str]], output_format: str = "markdown") -> str:
        """Generate a structured report in Markdown, HTML, or plain text."""
        if not self._running:
            raise RuntimeError("Agent not running")
        if output_format == "markdown":
            lines = [f"# {title}\n", f"*Generated by QUILL on {datetime.utcnow().isoformat()}*\n"]
            for sec in sections:
                lines.append(f"## {sec.get('heading', 'Section')}\n")
                lines.append(f"{sec.get('content', '')}\n")
            content = "\n".join(lines)
        elif output_format == "html":
            lines = [f"<h1>{title}</h1>", f"<p><em>Generated by QUILL on {datetime.utcnow().isoformat()}</em></p>"]
            for sec in sections:
                lines.append(f"<h2>{sec.get('heading', 'Section')}</h2>")
                lines.append(f"<p>{sec.get('content', '').replace(chr(10), '<br>')}</p>")
            content = "\n".join(lines)
        else:
            lines = [title, "=" * len(title), f"Generated: {datetime.utcnow().isoformat()}"]
            for sec in sections:
                lines.append(f"\n{sec.get('heading', 'Section')}\n{'-' * 40}")
                lines.append(sec.get("content", ""))
            content = "\n".join(lines)
        self._store_memory(f"report:{title}", {"format": output_format, "length": len(content)})
        return content

    def export_document(self, content: str, filepath: str, fmt: str = "md") -> Dict[str, Any]:
        """Export content to disk; attempt pandoc/weasyprint for PDF/DOCX."""
        if not self._running:
            raise RuntimeError("Agent not running")
        base, _ = os.path.splitext(filepath)
        out_path = f"{base}.{fmt}"
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(content)
        result = {"path": out_path, "format": fmt, "size_bytes": os.path.getsize(out_path)}
        if fmt == "pdf":
            rc, out, err = self._execute_shell(f"pandoc {out_path} -o {base}.pdf 2>&1 || weasyprint {out_path} {base}.pdf 2>&1", timeout=60)
            if rc == 0 and os.path.exists(f"{base}.pdf"):
                result["path"] = f"{base}.pdf"
                result["size_bytes"] = os.path.getsize(f"{base}.pdf")
            else:
                result["pdf_error"] = err or "PDF conversion failed; Markdown saved."
        elif fmt == "docx":
            rc, out, err = self._execute_shell(f"pandoc {out_path} -o {base}.docx 2>&1", timeout=60)
            if rc == 0 and os.path.exists(f"{base}.docx"):
                result["path"] = f"{base}.docx"
                result["size_bytes"] = os.path.getsize(f"{base}.docx")
            else:
                result["docx_error"] = err or "DOCX conversion failed; Markdown saved."
        self._store_memory(f"export:{filepath}", result)
        return result

    def auto_docs_from_code(self, source_path: str) -> Dict[str, Any]:
        """Parse Python source with AST and generate Markdown API docs."""
        if not self._running:
            raise RuntimeError("Agent not running")
        with open(source_path, "r", encoding="utf-8") as f:
            source = f.read()
        tree = ast.parse(source)
        docs: List[Dict[str, Any]] = []
        for node in ast.walk(tree):
            if isinstance(node, ast.ClassDef):
                methods = [n.name for n in node.body if isinstance(n, ast.FunctionDef)]
                docs.append({"type": "class", "name": node.name, "methods": methods, "line": node.lineno})
            elif isinstance(node, ast.FunctionDef):
                docs.append({"type": "function", "name": node.name, "line": node.lineno})
        md_lines = [f"# API Documentation: {os.path.basename(source_path)}", ""]
        for d in docs:
            if d["type"] == "class":
                md_lines.append(f"## Class `{d['name']}` (line {d['line']})")
                md_lines.append(f"Methods: {', '.join(d['methods'])}\n")
            else:
                md_lines.append(f"### `{d['name']}` (line {d['line']})")
        content = "\n".join(md_lines)
        self._store_memory(f"autodoc:{source_path}", {"symbols": len(docs)})
        return {"source": source_path, "symbols": docs, "markdown": content}

    def generate_presentation(self, title: str, slides: List[Dict[str, str]], engine: str = "revealjs") -> str:
        """Generate a self-contained HTML presentation (reveal.js inline)."""
        if not self._running:
            raise RuntimeError("Agent not running")
        if engine == "revealjs":
            slide_html = ""
            for s in slides:
                slide_html += f"<section><h2>{s.get('title','')}</h2><p>{s.get('content','').replace(chr(10),'<br>')}</p></section>\n"
            html = f"""<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>{title}</title>
<style>
body {{ margin:0; font-family: sans-serif; background:#111; color:#fff; }}
.slide {{ min-height:100vh; display:flex; flex-direction:column; justify-content:center; align-items:center; padding:2rem; box-sizing:border-box; border-bottom:1px solid #333; }}
h2 {{ margin:0 0 1rem; font-size:2.5rem; }}
p {{ max-width:800px; font-size:1.25rem; line-height:1.6; }}
</style></head><body>
{slide_html}
</body></html>"""
        else:
            lines = [f"# {title}", ""]
            for s in slides:
                lines.append(f"## {s.get('title','')}")
                lines.append(f"{s.get('content','')}\n")
            html = "\n".join(lines)
        self._store_memory(f"presentation:{title}", {"slides": len(slides), "engine": engine})
        return html

    def generate_changelog(self, commits: List[Dict[str, str]], style: str = "keepachangelog") -> str:
        """Generate a changelog from commit data."""
        if style == "keepachangelog":
            lines = ["# Changelog", "", "## [Unreleased]"]
            categories: Dict[str, List[str]] = {}
            for c in commits:
                msg = c.get("message", "")
                if msg.lower().startswith("feat"):
                    categories.setdefault("Added", []).append(msg)
                elif msg.lower().startswith("fix"):
                    categories.setdefault("Fixed", []).append(msg)
                elif msg.lower().startswith("deprec"):
                    categories.setdefault("Deprecated", []).append(msg)
                else:
                    categories.setdefault("Changed", []).append(msg)
            for cat, items in categories.items():
                lines.append(f"### {cat}")
                for item in items:
                    lines.append(f"- {item}")
                lines.append("")
            content = "\n".join(lines)
        else:
            lines = ["Changelog", "=" * 40]
            for c in commits:
                lines.append(f"- {c.get('hash','')[:7]}: {c.get('message','')}")
            content = "\n".join(lines)
        self._store_memory("changelog:latest", {"commits": len(commits)})
        return content

    # ------------------------------------------------------------------
    # Unit test stubs
    # ------------------------------------------------------------------
    def test_generate_report(self) -> bool:
        r = self.generate_report("Test", [{"heading": "H1", "content": "C1"}], "markdown")
        return "# Test" in r

    def test_export_document(self) -> bool:
        import tempfile
        with tempfile.NamedTemporaryFile(mode="w", suffix=".md", delete=False) as f:
            f.write("# Hello")
            path = f.name
        r = self.export_document("# Hello", path, "md")
        return os.path.exists(r["path"])

    def test_auto_docs(self) -> bool:
        import tempfile
        with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False) as f:
            f.write("class Foo:\n    def bar(self):\n        pass\n")
            path = f.name
        r = self.auto_docs_from_code(path)
        return any(s["name"] == "Foo" for s in r["symbols"])

    def test_generate_presentation(self) -> bool:
        r = self.generate_presentation("T", [{"title": "S1", "content": "C1"}], "revealjs")
        return "<section>" in r

    def test_generate_changelog(self) -> bool:
        r = self.generate_changelog([{"hash": "abc123", "message": "feat: add X"}], "keepachangelog")
        return "Added" in r


