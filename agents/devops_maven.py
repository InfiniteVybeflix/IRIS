    def _execute_impl(self, task: Task) -> Any:
        payload = task.payload
        request = payload.get("original_request", task.description).lower()

        if any(kw in request for kw in ["docker", "dockerfile", "container"]):
            return self.generate_dockerfile(payload)
        elif any(kw in request for kw in ["kubernetes", "k8s", "pod", "deployment", "service"]):
            return self.generate_kubernetes(payload)
        elif any(kw in request for kw in ["ci/cd", "pipeline", "github action", "gitlab ci", "jenkins"]):
            return self.generate_cicd_pipeline(payload)
        elif any(kw in request for kw in ["terraform", "infrastructure", "iac"]):
            return self.generate_terraform(payload)
        elif any(kw in request for kw in ["monitor", "prometheus", "grafana", "alert"]):
            return self.setup_monitoring(payload)
        elif any(kw in request for kw in ["log", "elk", "loki", "aggregation"]):
            return self.setup_logging(payload)
        elif any(kw in request for kw in ["helm", "chart"]):
            return self.generate_helm_chart(payload)
        elif any(kw in request for kw in ["nginx", "traefik", "reverse proxy", "load balancer"]):
            return self.generate_proxy_config(payload)
        else:
            return self.generate_full_devops_stack(payload)

