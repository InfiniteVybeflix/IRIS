    def generate_proxy_config(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        """Generate reverse proxy configuration."""
        proxy_type = payload.get("proxy_type", "nginx")

        if proxy_type == "nginx":
            config = self._generate_nginx_config()
        elif proxy_type == "traefik":
            config = self._generate_traefik_config()
        else:
            config = self._generate_nginx_config()

        return {
            "proxy_type": proxy_type,
            "config": config,
            "ssl_renewal": "certbot renew --dry-run",
        }

